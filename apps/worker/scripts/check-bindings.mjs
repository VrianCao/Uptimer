// Wrangler 4.61's --check drops --env-file and can compare local secrets against
// binding-only types. Regenerate with the same arguments and compare the types.
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
const worker = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const binary = join(dirname(require.resolve('wrangler/package.json')), 'bin/wrangler.js');
await mkdir(join(worker, '.wrangler'), { recursive: true });
const directory = await mkdtemp(join(worker, '.wrangler/types-check-'));
const output = join(directory, 'bindings.d.ts');
function comparable(source, path) {
  return source
    .replace(/\r\n/g, '\n')
    .replace(/^\/\/ Generated by Wrangler.*\n/m, '')
    .replace(/import\("([^"\n]+)"\)/g, (_match, name) => {
      if (!name.startsWith('.')) return `import("${name}")`;
      const target = relative(worker, resolve(dirname(path), name))
        .split(sep)
        .join('/');
      return `import("${target}")`;
    });
}
try {
  await new Promise((resolve, reject) => {
    const child = spawn(
      process.execPath,
      [
        binary,
        'types',
        output,
        '--env-interface',
        'WorkerBindings',
        '--include-runtime',
        'false',
        '--strict-vars',
        'false',
        '--env-file',
        'bindings.env',
      ],
      {
        cwd: worker,
        env: { ...process.env, CLOUDFLARE_INCLUDE_PROCESS_ENV: 'false' },
        stdio: 'ignore',
      },
    );
    child.on('error', reject);
    child.on('exit', (code) =>
      code === 0 ? resolve() : reject(new Error('Wrangler binding type generation failed')),
    );
  });
  const current = join(worker, 'src/worker-configuration.d.ts');
  if (
    comparable(await readFile(output, 'utf8'), output) !==
    comparable(await readFile(current, 'utf8'), current)
  )
    throw new Error(
      'Worker binding types are out of date; run pnpm --filter @uptimer/worker types',
    );
  console.log('Worker binding types match wrangler.toml independently of local secrets');
} finally {
  await rm(directory, { recursive: true, force: true });
}
